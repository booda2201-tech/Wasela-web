/**
 * Writes src/environments/version.ts so the footer shows which build the user is looking at.
 *
 * Runs automatically from webpack.version.js on every `ng build` / `ng serve`.
 * A build (`bump = true`) increases the build number in build-number.json,
 * so every new build gets a new version (v1.0.1, v1.0.2, ...) even on the same day.
 * Serve just shows the current number.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');

function generateVersion({ bump = false } = {}) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const counterFile = path.join(root, 'build-number.json');

  let build = 0;
  if (fs.existsSync(counterFile)) {
    build = Number(JSON.parse(fs.readFileSync(counterFile, 'utf8')).build) || 0;
  }
  if (bump) {
    build += 1;
    fs.writeFileSync(counterFile, JSON.stringify({ build }, null, 2) + '\n');
  }

  const [major = '1', minor = '0'] = String(pkg.version).split('.');
  const version = `${major}.${minor}.${build}`;

  const content = `// Auto-generated by scripts/generate-version.js — do not edit by hand.
export const APP_VERSION = {
  version: '${version}',
};
`;

  const target = path.join(root, 'src', 'environments', 'version.ts');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    fs.writeFileSync(target, content);
  }
  console.log(`[version] v${version}`);
}

module.exports = { generateVersion };

if (require.main === module) {
  generateVersion({ bump: process.argv.includes('--bump') });
}
