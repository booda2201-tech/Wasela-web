/**
 * Writes src/environments/version.ts so the footer shows which build the user is looking at.
 *
 * Runs automatically from webpack.version.js. Every `ng build` gets a version built from
 * the build time (Cairo): v<major>.<MMDD>.<HHmm>, e.g. v1.1109.1533 — so it changes on
 * every build on any machine (local, Vercel, ...) without keeping a counter file.
 * `ng serve` keeps the version of the last build.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const target = path.join(root, 'src', 'environments', 'version.ts');

function generateVersion({ isBuild = false } = {}) {
  if (!isBuild && fs.existsSync(target)) {
    return;
  }

  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const [major = '1'] = String(pkg.version).split('.');

  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Cairo',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).formatToParts(new Date());
  const get = (type) => parts.find((p) => p.type === type).value;
  const version = `${major}.${get('month')}${get('day')}.${get('hour')}${get('minute')}`;

  const content = `// Auto-generated by scripts/generate-version.js — do not edit by hand.
export const APP_VERSION = {
  version: '${version}',
};
`;

  fs.writeFileSync(target, content);
  console.log(`[version] v${version}`);
}

module.exports = { generateVersion };

if (require.main === module) {
  generateVersion({ isBuild: true });
}
