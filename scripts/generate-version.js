/**
 * Writes src/environments/version.ts so the footer shows which build the user is looking at.
 *
 * `--bump` (used by `npm run build`) increases the build number in build-number.json,
 * so every new build gets a new version (v1.0.1, v1.0.2, ...) even on the same day.
 * `npm start` runs without `--bump` and just shows the current number.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const counterFile = path.join(root, 'build-number.json');

let build = 0;
if (fs.existsSync(counterFile)) {
  build = Number(JSON.parse(fs.readFileSync(counterFile, 'utf8')).build) || 0;
}
if (process.argv.includes('--bump')) {
  build += 1;
  fs.writeFileSync(counterFile, JSON.stringify({ build }, null, 2) + '\n');
}

const [major = '1', minor = '0'] = String(pkg.version).split('.');
const version = `${major}.${minor}.${build}`;

const parts = new Intl.DateTimeFormat('en-GB', {
  timeZone: 'Africa/Cairo',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
}).formatToParts(new Date());
const get = (type) => parts.find((p) => p.type === type).value;
const buildDate = `${get('year')}-${get('month')}-${get('day')}`;

const content = `// Auto-generated by scripts/generate-version.js — do not edit by hand.
export const APP_VERSION = {
  version: '${version}',
  buildDate: '${buildDate}',
};
`;

fs.writeFileSync(path.join(root, 'src', 'environments', 'version.ts'), content);
console.log(`[version] v${version} (${buildDate})`);
